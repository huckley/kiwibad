int getBatteryLevel(float voltage) {
  // Typische Li-Po Spannungsstufen für 8 Icons (Level 0 bis 7)
  if (voltage > 4.15) return 7; // Full
  if (voltage > 4.00) return 6;
  if (voltage > 3.85) return 5;
  if (voltage > 3.75) return 4;
  if (voltage > 3.65) return 3;
  if (voltage > 3.55) return 2;
  if (voltage > 3.40) return 1;
  return 0; // Leer (< 3.4V)
}

void battery() {
  pinMode(ADC_CTRL, OUTPUT);
  digitalWrite(ADC_CTRL, !ADC_CTRL_ENABLED);
  analogReadResolution(12);
  delay(50);
  int analogVolts = analogReadMilliVolts(BATTERY_PIN);
  float batteryVoltage = analogVolts * 490 / 100000;
  int level = getBatteryLevel(batteryVoltage);

  const uint8_t* icons[] = {battery0, battery1, battery2, battery3, battery4, battery5, battery6, batteryfull};
  Serial.printf("Voltage: %.3f\n", batteryVoltage);
  oled_display.drawXbm(110, 0, battery_w, battery_h, icons[level]);
}
